package BitManipulation;

public class BitManipulation {
    public static void main(String[] args) {
        //? Binary AND
        System.out.println(5&6);

        //? Binary OR
        System.out.println(5|6);

        //? Binary XOR
        System.out.println(5^6);

        //? Binary Ones Cpmplement
        System.out.println(~5);

        //? Binary Left Shift
        System.out.println(5<<2);           //! Formula - a << b = a * 2^b

        //? Binary Right Shift
        System.out.println(6>>1);           //! Formula - a >> b = a / 2^b
        
        
    }
}
